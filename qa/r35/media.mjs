import { chromium } from 'playwright';
import { writeFile } from 'node:fs/promises';
const browser=await chromium.launch({headless:true,...(process.env.CI?{}:{channel:'chrome'})});
const page=await browser.newPage({viewport:{width:390,height:844}});
const results=[];
const check=(name,pass)=>{results.push({name,pass:!!pass});console.log(`${pass?'PASS':'FAIL'} ${name}`);};
await page.goto(process.env.R35_URL || 'http://127.0.0.1:8350/sense-r35/',{waitUntil:'networkidle'});
await page.locator('#video-toggle').click();
await page.waitForFunction(()=>!document.querySelector('video').paused&&document.querySelector('video').currentTime>0.15);
check('MP4 decodes and plays after explicit request',await page.locator('video').evaluate(v=>v.videoWidth>0&&v.currentTime>0));
await page.locator('#video-toggle').click();
check('Stop restores poster',await page.locator('video').evaluate(v=>v.paused)&&!await page.locator('.is-playing').count());
await page.locator('#video-toggle').click();
await page.waitForFunction(()=>!document.querySelector('video').paused);
await page.locator('#sense-os').scrollIntoViewIfNeeded();
await page.waitForFunction(()=>document.querySelector('video').paused);
check('Leaving scene stops playback',await page.locator('video').evaluate(v=>v.paused));
await page.locator('#video-toggle').click();
await page.waitForFunction(()=>!document.querySelector('video').paused);
await page.emulateMedia({reducedMotion:'reduce'});
await page.waitForFunction(()=>document.querySelector('video').paused);
check('Live reduced-motion stops video and hides control',await page.locator('video').evaluate(v=>v.paused)&&!await page.locator('#video-toggle').isVisible());
await browser.close();
await writeFile(new URL('../../evidence/r35/media-results.json',import.meta.url),JSON.stringify({results,passed:results.filter(r=>r.pass).length,failed:results.filter(r=>!r.pass).length},null,2));
process.exitCode=results.every(r=>r.pass)?0:1;
